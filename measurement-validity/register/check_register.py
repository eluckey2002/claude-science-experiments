"""Validate the instrument-failure register and regenerate summary.md.

Run from anywhere:  python measurement-validity/register/check_register.py [--write]
Exit code 0 = valid.  Every number in summary.md is computed here, never typed.
"""
import sys
from pathlib import Path
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
studies = pd.read_csv(HERE / "studies.csv").fillna("")
fails = pd.read_csv(HERE / "failures.csv").fillna("")
types = pd.read_csv(HERE / "failure_types.csv")

ENUMS = {
    ("studies", "kind"): {"comparison", "instrument_check", "rating_scheme"},
    ("studies", "outcome"): {"RESULT", "NO_RESULT", "NOT_RUN"},
    ("studies", "spend"): {"MODEL_CALLS", "NONE", "INHERITED", "NOT_RECORDED"},
    ("studies", "instrument_status"): {"HELD", "NOT_CHECKED", "PARTLY_FAILED", "FAILED"},
    ("failures", "cause_status"): {"DIAGNOSED", "MEASURED_NOT_EXPLAINED", "INFERRED"},
    ("failures", "prevention_status"): {"GUARDED", "PARTLY", "NONE"},
    ("failures", "caught_when"): {"BEFORE_SPEND", "AFTER_SPEND"},
}
errors = []

def need(cond, msg):
    if not cond:
        errors.append(msg)

for (table, col), allowed in ENUMS.items():
    df = studies if table == "studies" else fails
    bad = sorted(set(df[col]) - allowed)
    need(not bad, f"{table}.{col} has values outside {sorted(allowed)}: {bad}")

need(studies.study_id.is_unique, "duplicate study_id")
need(fails.failure_id.is_unique, "duplicate failure_id")
need(set(fails.study_id) <= set(studies.study_id), "failure points at an unknown study_id")
need(set(fails.failure_type) <= set(types.failure_type), "failure_type not in failure_types.csv: "
     + str(sorted(set(fails.failure_type) - set(types.failure_type))))

n_by_study = fails.groupby("study_id").size()
for r in studies.itertuples():
    n = int(n_by_study.get(r.study_id, 0))
    if r.instrument_status in ("FAILED", "PARTLY_FAILED"):
        need(n >= 1, f"{r.study_id} is {r.instrument_status} but has no failure row")
    else:
        need(n == 0, f"{r.study_id} is {r.instrument_status} but has {n} failure row(s)")
    if r.spend == "NONE":
        need(r.outcome in ("NOT_RUN", "RESULT"), f"{r.study_id}: spend NONE needs outcome NOT_RUN or RESULT")
    if r.outcome == "NOT_RUN":
        need(r.spend == "NONE", f"{r.study_id}: NOT_RUN must have spend NONE")

# A failure marked BEFORE_SPEND must belong to a study with no model-call spend.
join = fails.merge(studies[["study_id", "spend", "outcome"]], on="study_id")
bad = join[(join.caught_when == "BEFORE_SPEND") & (join.spend == "MODEL_CALLS") & (join.outcome != "NOT_RUN")]
need(bad.empty, "BEFORE_SPEND failure on a study that already spent model calls: " + str(list(bad.failure_id)))

# Evidence paths must exist (paths starting ext: point outside this repo and are not checked).
for label, df, col, idcol in (("studies", studies, "evidence", "study_id"), ("failures", fails, "evidence", "failure_id")):
    for r in df.itertuples():
        for p in str(getattr(r, col)).split(";"):
            p = p.strip()
            if p and not p.startswith("ext:"):
                need((ROOT / p).exists(), f"{label} {getattr(r, idcol)}: evidence path missing: {p}")

def table(df):
    return "\n".join(["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
                     + ["| " + " | ".join(map(str, row)) + " |" for row in df.itertuples(index=False)])

def summary():
    ns, nf = len(studies), len(fails)
    bad_studies = studies[studies.instrument_status.isin(["FAILED", "PARTLY_FAILED"])]
    late = int((fails.caught_when == "AFTER_SPEND").sum()); early = nf - late
    out = ["# Register summary", "", "Generated by check_register.py. Do not edit by hand.", ""]
    out += [f"- Studies in the register: {ns}",
            f"- Studies whose instrument failed or partly failed: {len(bad_studies)} ({len(bad_studies)/ns:.0%})",
            f"- Failure rows: {nf}; caught before any model call: {early}; caught after spend: {late} ({late/nf:.0%})",
            f"- Failure rows with a cause diagnosed: {int((fails.cause_status=='DIAGNOSED').sum())} of {nf}",
            f"- Failure rows with no prevention in place: {int((fails.prevention_status=='NONE').sum())} of {nf}; partly guarded: {int((fails.prevention_status=='PARTLY').sum())}; guarded: {int((fails.prevention_status=='GUARDED').sum())}",
            "", "The number to drive down is the share of failures caught after spend.", ""]
    out += ["## Instrument status of all studies", "", table(studies.groupby("instrument_status").size().rename("studies").reset_index()), ""]
    out += ["## Failures by type", "", table(fails.groupby("failure_type").agg(
        failures=("failure_id", "count"),
        after_spend=("caught_when", lambda s: int((s == "AFTER_SPEND").sum())),
        no_prevention=("prevention_status", lambda s: int((s == "NONE").sum()))).reset_index().sort_values("failures", ascending=False)), ""]
    wk = studies.merge(fails.groupby("study_id").agg(nf=("failure_id", "count"),
            late=("caught_when", lambda s: int((s == "AFTER_SPEND").sum()))).reset_index(), on="study_id", how="left").fillna({"nf": 0, "late": 0})
    wk["week_of"] = (pd.to_datetime(wk.date) - pd.to_timedelta(pd.to_datetime(wk.date).dt.weekday, unit="D")).dt.strftime("%Y-%m-%d")
    t = wk.groupby("week_of").agg(studies=("study_id", "count"), failures=("nf", "sum"), after_spend=("late", "sum")).reset_index()
    t[["failures", "after_spend"]] = t[["failures", "after_spend"]].astype(int)
    out += ["## By week of study date", "", table(t.astype(str)), ""]
    return "\n".join(out)

if errors:
    print("INVALID"); [print(" -", e) for e in errors]; sys.exit(1)
s = summary()
if "--write" in sys.argv:
    (HERE / "summary.md").write_text(s)
print(s)
